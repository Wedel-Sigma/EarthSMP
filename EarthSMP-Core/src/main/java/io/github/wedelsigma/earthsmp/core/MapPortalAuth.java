package io.github.wedelsigma.earthsmp.core;

import java.nio.charset.StandardCharsets;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.security.SecureRandom;
import java.security.spec.KeySpec;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.time.Clock;
import java.time.Duration;
import java.time.Instant;
import java.util.Base64;
import java.util.HashMap;
import java.util.HexFormat;
import java.util.Locale;
import java.util.Map;
import java.util.Optional;
import java.util.UUID;
import javax.crypto.SecretKeyFactory;
import javax.crypto.spec.PBEKeySpec;

/**
 * A one-time Minecraft pairing links a UUID to a password-protected web account.
 * Accounts and hashed session tokens live in earthsmp.db and survive restarts.
 * All access to this separate SQLite connection is synchronized. Bukkit is never touched here.
 */
final class MapPortalAuth implements AutoCloseable {
    private static final String ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789";
    private static final Duration CODE_TTL = Duration.ofMinutes(5);
    static final long COOKIE_MAX_AGE = Duration.ofDays(30).toSeconds();
    private static final Duration SESSION_TTL = Duration.ofDays(30);
    private static final Duration LIMIT_PERIOD = Duration.ofMinutes(10);
    private static final int MAX_FAILURES_PER_ADDRESS = 6;
    private static final int KDF_ITERATIONS = 210_000;
    private static final int MIN_PASSWORD_LENGTH = 12;
    private static final byte[] DUMMY_SALT = new byte[16];

    record SessionToken(String token, UUID player) {}
    private record Pending(String hash, String username, Instant expires) {}
    private record Failures(int count, Instant until) {}

    private final SecureRandom random = new SecureRandom();
    private final Clock clock;
    private final Connection database;
    private final Map<UUID, Pending> pending = new HashMap<>();
    private final Map<String, Failures> attempts = new HashMap<>();

    MapPortalAuth(Path file) throws SQLException { this(file, Clock.systemUTC()); }

    MapPortalAuth(Path file, Clock clock) throws SQLException {
        this.clock = clock;
        database = DriverManager.getConnection("jdbc:sqlite:" + file.toAbsolutePath());
        try (Statement statement = database.createStatement()) {
            statement.execute("PRAGMA foreign_keys=ON");
            statement.execute("PRAGMA busy_timeout=5000");
            try (ResultSet version = statement.executeQuery("PRAGMA user_version")) {
                if (!version.next() || version.getInt(1) < 9) {
                    throw new SQLException("Map accounts need SQLite schema v9; update NationDatabase first");
                }
            }
        } catch (SQLException | RuntimeException failure) {
            try { database.close(); } catch (SQLException e) { failure.addSuppressed(e); }
            throw failure;
        }
    }

    synchronized boolean hasAccount(UUID player) throws SQLException {
        try (PreparedStatement query = database.prepareStatement(
                "SELECT 1 FROM map_accounts WHERE player_uuid=?")) {
            query.setString(1, player.toString());
            try (ResultSet result = query.executeQuery()) { return result.next(); }
        }
    }

    /** One-time enrollment code generated by a verified, online Minecraft player. */
    synchronized Optional<String> issue(UUID player, String name) throws SQLException {
        prune();
        if (hasAccount(player)) return Optional.empty();
        if (name == null || !name.matches("[A-Za-z0-9_]{3,16}")) return Optional.empty();
        StringBuilder value = new StringBuilder(10);
        for (int i = 0; i < 10; i++) value.append(ALPHABET.charAt(random.nextInt(ALPHABET.length())));
        String code = value.toString();
        pending.put(player, new Pending(sha256(code), name, clock.instant().plus(CODE_TTL)));
        return Optional.of(code);
    }

    /** First pairing creates the persistent account and immediately signs into this browser. */
    synchronized Optional<SessionToken> redeem(String submitted, String password, String address) throws SQLException {
        prune();
        if (blocked(address)) return Optional.empty();
        String input = submitted == null ? "" : submitted.trim().toUpperCase(Locale.ROOT);
        String hash = sha256(input);
        UUID match = null;
        Pending enrollment = null;
        for (var entry : pending.entrySet()) {
            if (MessageDigest.isEqual(hash.getBytes(StandardCharsets.US_ASCII),
                    entry.getValue().hash().getBytes(StandardCharsets.US_ASCII))) {
                match = entry.getKey();
                enrollment = entry.getValue();
            }
        }
        if (match == null || !validPassword(password) || hasAccount(match)) {
            registerFailure(address);
            return Optional.empty();
        }
        byte[] salt = new byte[16];
        random.nextBytes(salt);
        byte[] derived = derive(password, salt);
        var token = newToken(match);
        database.setAutoCommit(false);
        try {
            try (PreparedStatement q = database.prepareStatement(
                    "INSERT INTO map_accounts(player_uuid, username, password_salt, password_hash) VALUES(?,?,?,?)")) {
                q.setString(1, match.toString());
                q.setString(2, enrollment.username());
                q.setBytes(3, salt);
                q.setBytes(4, derived);
                q.executeUpdate();
            }
            storeSession(token);
            database.commit();
        } catch (SQLException | RuntimeException error) {
            database.rollback();
            throw error;
        } finally { database.setAutoCommit(true); }
        pending.remove(match);
        attempts.remove(address);
        return Optional.of(token);
    }

    /** Later sign-ins from ANY device need only the nickname and password, never another in-game code. */
    synchronized Optional<SessionToken> login(String username, String password, String address) throws SQLException {
        prune();
        if (blocked(address)) return Optional.empty();
        String nick = username == null ? "" : username.trim();
        byte[] salt = DUMMY_SALT;
        byte[] expected = null;
        UUID player = null;
        if (nick.matches("[A-Za-z0-9_]{3,16}")) {
            try (PreparedStatement q = database.prepareStatement(
                    "SELECT player_uuid,password_salt,password_hash FROM map_accounts WHERE username=? COLLATE NOCASE")) {
                q.setString(1, nick);
                try (ResultSet result = q.executeQuery()) {
                    if (result.next()) {
                        player = UUID.fromString(result.getString(1));
                        salt = result.getBytes(2);
                        expected = result.getBytes(3);
                    }
                }
            }
        }
        // Unknown accounts still perform a KDF to avoid a username-enumeration timing oracle.
        byte[] computed = derive(password == null ? "" : password, salt);
        if (player == null || !MessageDigest.isEqual(computed, expected)) {
            registerFailure(address);
            return Optional.empty();
        }
        var token = newToken(player);
        storeSession(token);
        attempts.remove(address);
        return Optional.of(token);
    }

    synchronized Optional<UUID> authenticate(String token) throws SQLException {
        if (token == null || token.length() != 43) return Optional.empty();
        try (PreparedStatement q = database.prepareStatement(
                "SELECT player_uuid,expires_at FROM map_sessions WHERE token_hash=?")) {
            q.setString(1, sha256(token));
            try (ResultSet r = q.executeQuery()) {
                if (!r.next() || !clock.instant().isBefore(Instant.ofEpochSecond(r.getLong(2)))) return Optional.empty();
                return Optional.of(UUID.fromString(r.getString(1)));
            }
        }
    }

    synchronized void logout(String token) throws SQLException {
        if (token == null || token.length() != 43) return;
        try (PreparedStatement q = database.prepareStatement("DELETE FROM map_sessions WHERE token_hash=?")) {
            q.setString(1, sha256(token));
            q.executeUpdate();
        }
    }

    /** Revokes all browser sessions, but preserves the linked password-based account. */
    synchronized void revoke(UUID player) throws SQLException {
        pending.remove(player);
        try (PreparedStatement q = database.prepareStatement("DELETE FROM map_sessions WHERE player_uuid=?")) {
            q.setString(1, player.toString());
            q.executeUpdate();
        }
    }

    /** In-game recovery: forget this account and all browser sessions; issue a fresh pairing code. */
    synchronized void reset(UUID player) throws SQLException {
        pending.remove(player);
        try (PreparedStatement q = database.prepareStatement("DELETE FROM map_accounts WHERE player_uuid=?")) {
            q.setString(1, player.toString());
            q.executeUpdate();
        }
    }

    /** Read on Paper main thread, but using this auth-only connection. Includes offline viewers. */
    synchronized Map<UUID, String> linkedAccounts() throws SQLException {
        var result = new HashMap<UUID, String>();
        try (PreparedStatement q = database.prepareStatement("SELECT player_uuid,username FROM map_accounts");
             ResultSet rows = q.executeQuery()) {
            while (rows.next()) result.put(UUID.fromString(rows.getString(1)), rows.getString(2));
        }
        return Map.copyOf(result);
    }

    @Override public synchronized void close() throws SQLException {
        pending.clear(); attempts.clear(); database.close();
    }

    private boolean blocked(String address) {
        Failures fail = attempts.get(address);
        return fail != null && fail.count() >= MAX_FAILURES_PER_ADDRESS && clock.instant().isBefore(fail.until());
    }
    private void registerFailure(String address) {
        Instant now = clock.instant();
        Failures old = attempts.get(address);
        int count = old == null || !now.isBefore(old.until()) ? 1 : old.count() + 1;
        attempts.put(address, new Failures(count, now.plus(LIMIT_PERIOD)));
    }
    private void prune() {
        Instant now = clock.instant();
        pending.entrySet().removeIf(e -> !now.isBefore(e.getValue().expires()));
        attempts.entrySet().removeIf(e -> !now.isBefore(e.getValue().until()));
    }
    private SessionToken newToken(UUID player) {
        byte[] raw = new byte[32]; random.nextBytes(raw);
        return new SessionToken(Base64.getUrlEncoder().withoutPadding().encodeToString(raw), player);
    }
    private void storeSession(SessionToken token) throws SQLException {
        try (PreparedStatement q = database.prepareStatement(
                "INSERT INTO map_sessions(token_hash,player_uuid,expires_at) VALUES(?,?,?)")) {
            q.setString(1, sha256(token.token()));
            q.setString(2, token.player().toString());
            q.setLong(3, clock.instant().plus(SESSION_TTL).getEpochSecond());
            q.executeUpdate();
        }
    }
    static boolean validPassword(String password) {
        return password != null && password.length() >= MIN_PASSWORD_LENGTH && password.length() <= 128;
    }
    private static byte[] derive(String password, byte[] salt) {
        char[] chars = password.toCharArray();
        KeySpec spec = new PBEKeySpec(chars, salt, KDF_ITERATIONS, 256);
        try {
            return SecretKeyFactory.getInstance("PBKDF2WithHmacSHA256").generateSecret(spec).getEncoded();
        } catch (Exception error) { throw new IllegalStateException("PBKDF2 unavailable", error); }
        finally { java.util.Arrays.fill(chars, '\0'); }
    }
    private static String sha256(String value) {
        try {
            byte[] bytes = MessageDigest.getInstance("SHA-256").digest(value.getBytes(StandardCharsets.UTF_8));
            return HexFormat.of().formatHex(bytes);
        } catch (NoSuchAlgorithmException e) { throw new IllegalStateException(e); }
    }
}
